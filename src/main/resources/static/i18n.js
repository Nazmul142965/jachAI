// Translate one piece: exact, then by pattern. Null when nothing recognises it.
function piece(text) {
  if (Object.hasOwn(BN, text)) return BN[text];
  // A pattern's "(.+)" would swallow every " · " piece after it, so a joined sentence is split first.
  if (text.includes(' · ')) return null;
  for (const [pattern, build] of PATTERNS) {
    const match = pattern.exec(text);
    if (match) return build(match);
  }
  return null;
}
// What the reader sees in a piece that has a translation inside it, e.g. "(you are Org Admin)".
function tx(text) { return piece(text) ?? text; }
// The whole text, or each " · " piece of it. Null when no piece is recognised.
function translateComposite(text) {
  const whole = piece(text);
  if (whole !== null) return whole;
  if (!text.includes(' · ')) return translateSentences(text);
  let any = false;
  const pieces = text.split(' · ').map((part) => {
    const done = piece(part.trim());
    if (done !== null) { any = true; return done; }
    return part;
  });
  return any ? pieces.join(' · ') : null;
}
// "A. B. C." built by joining sentences that are each in the dictionary.
function translateSentences(text) {
  const sentences = text.split(/(?<=[.!?])\s+/);
  if (sentences.length < 2) return null;
  let any = false;
  const done = sentences.map((sentence) => {
    const result = piece(sentence);
    if (result !== null) { any = true; return result; }
    return sentence;
  });
  return any ? done.join(' ') : null;
}
// Dates and times follow the language without every call site passing a locale.
for (const method of ['toLocaleString', 'toLocaleDateString', 'toLocaleTimeString']) {
  const original = Date.prototype[method];
  Date.prototype[method] = function (locales, ...rest) {
    return original.call(this, locales ?? (language === 'bn' ? 'bn-BD' : undefined), ...rest);
  };
}

const originals = new WeakMap();
const attributeOriginals = new WeakMap();
const ATTRIBUTES = ['placeholder', 'aria-label', 'title'];
const SKIPPED = 'script, style, textarea, input, select option:checked, [data-no-translate]';
const collapse = (text) => text.replace(/\s+/g, ' ').trim();

function translateTextNode(node) {
  if (node.parentElement?.closest(SKIPPED)) return;
  const remembered = originals.get(node);
  const source = remembered ?? node.nodeValue;
  const key = collapse(source);
  if (!key) return;
  const translated = language === 'bn' ? translateComposite(key) : null;
  if (translated !== null) {
    if (remembered === undefined) originals.set(node, node.nodeValue);
    const lead = source.match(/^\s*/)[0]; const trail = source.match(/\s*$/)[0];
    node.nodeValue = lead + translated + trail;
  } else if (language !== 'bn' && remembered !== undefined) {
    node.nodeValue = remembered;
    originals.delete(node);
  }
}
function translateAttributes(element) {
  for (const attribute of ATTRIBUTES) {
    if (!element.hasAttribute?.(attribute)) continue;
    const saved = attributeOriginals.get(element) || {};
    const source = saved[attribute] ?? element.getAttribute(attribute);
    const key = collapse(source);
    const translatedAttribute = language === 'bn' ? translateComposite(key) : null;
    if (translatedAttribute !== null) {
      saved[attribute] = source; attributeOriginals.set(element, saved);
      element.setAttribute(attribute, translatedAttribute);
    } else if (language !== 'bn' && saved[attribute] !== undefined) {
      element.setAttribute(attribute, saved[attribute]);
      delete saved[attribute];
    }
  }
}
export function translateTree(root = document.body) {
  if (!root) return;
  if (root.nodeType === Node.TEXT_NODE) { translateTextNode(root); return; }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  translateAttributes(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.nodeType === Node.TEXT_NODE) translateTextNode(node); else translateAttributes(node);
  }
}
// Text the screens add later is translated as it arrives.
let observer = null;
function watch() {
  if (observer || typeof MutationObserver === 'undefined' || !document.body) return;
  observer = new MutationObserver((records) => {
    if (language !== 'bn') return;
    for (const record of records) for (const added of record.addedNodes) translateTree(added);
  });
  observer.observe(document.body, { childList: true, subtree: true });
}

// Re-labels every element that opted in, and then everything else the dictionary knows.
export function applyLanguage(root = document) {
  document.documentElement.lang = language === 'bn' ? 'bn' : 'en';
  for (const element of root.querySelectorAll('[data-t]')) {
    if (element.dataset.en === undefined) element.dataset.en = element.textContent.trim();
    element.textContent = t(element.dataset.en);
  }
  for (const attribute of ['placeholder', 'aria-label', 'title']) {
    for (const element of root.querySelectorAll(`[data-t-${attribute}]`)) {
      const key = `en${attribute.replace('-', '')}`;
      if (element.dataset[key] === undefined) element.dataset[key] = element.getAttribute(attribute) || '';
      element.setAttribute(attribute, t(element.dataset[key]));
    }
  }
  translateTree(document.body);
  watch();
}

export function setLanguage(next) {
  language = next === 'bn' ? 'bn' : 'en';
  try { localStorage.setItem('jachaiLang', language); } catch { /* not persisted; still applies now */ }
  applyLanguage();
  document.dispatchEvent(new CustomEvent('jachai:language', { detail: language }));
}
